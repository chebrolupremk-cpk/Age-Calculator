/* =========================================================
   GAME STATE
   ========================================================= */

let coins = Number(localStorage.getItem("riddleCoins")) || 0;

let solvedRiddles =
    JSON.parse(localStorage.getItem("solvedRiddles")) || [];

let currentRiddle = null;
let hintUsed = false;


/* =========================================================
   HTML ELEMENTS
   ========================================================= */

const coinsElement = document.getElementById("coinCount");
const progressElement = document.getElementById("progress");
const riddleNumberElement = document.getElementById("riddleNumber");
const difficultyElement = document.getElementById("difficulty");
const riddleQuestionElement =
    document.getElementById("riddleQuestion");

const answerInput =
    document.getElementById("answerInput");

const messageElement =
    document.getElementById("message");

const hintElement =
    document.getElementById("hintBox");

const submitButton =
    document.getElementById("submitAnswer");

const hintButton =
    document.getElementById("hintButton");

const nextButton =
    document.getElementById("nextButton");


/* =========================================================
   SAVE PROGRESS
   ========================================================= */

function saveProgress() {

    localStorage.setItem("riddleCoins", coins);

    localStorage.setItem(
        "solvedRiddles",
        JSON.stringify(solvedRiddles)
    );
}


/* =========================================================
   UPDATE DISPLAY
   ========================================================= */

function updateDisplay() {

    if (coinsElement) {
        coinsElement.textContent = coins;
    }

    if (progressElement) {
        progressElement.textContent =
            `Solved: ${solvedRiddles.length} / ${riddles.length}`;
    }
}


/* =========================================================
   GET UNSOLVED RIDDLES
   ========================================================= */

function getAvailableRiddles() {

    return riddles.filter(function (riddle) {

        return !solvedRiddles.includes(riddle.id);

    });

}


/* =========================================================
   DIFFICULTY
   ========================================================= */

function getDifficulty(id) {

    if (id <= 20) {
        return "Class 5";
    }

    if (id <= 40) {
        return "Class 10";
    }

    return "Intermediate";
}


/* =========================================================
   LOAD NEXT RIDDLE
   ========================================================= */

function loadNextRiddle() {

    const available = getAvailableRiddles();

    hintUsed = false;

    if (messageElement) {
        messageElement.textContent = "";
    }

    if (hintElement) {
        hintElement.textContent = "";
        hintElement.hidden = true;
    }

    if (answerInput) {
        answerInput.value = "";
        answerInput.disabled = false;
        answerInput.style.display = "";
    }

    if (submitButton) {
        submitButton.disabled = false;
        submitButton.style.display = "";
    }

    if (hintButton) {
        hintButton.disabled = false;
        hintButton.style.display = "";
    }

    if (nextButton) {
        nextButton.style.display = "none";
    }

    if (available.length === 0) {

        currentRiddle = null;

        if (riddleNumberElement) {
            riddleNumberElement.textContent =
                "🎉 Challenge Complete!";
        }

        if (difficultyElement) {
            difficultyElement.textContent =
                "All 50 Riddles Solved";
        }

        if (riddleQuestionElement) {
            riddleQuestionElement.textContent =
                "Amazing! You solved all 50 riddles!";
        }

        if (answerInput) {
            answerInput.style.display = "none";
        }

        if (submitButton) {
            submitButton.style.display = "none";
        }

        if (hintButton) {
            hintButton.style.display = "none";
        }

        if (nextButton) {
            nextButton.style.display = "none";
        }

        updateDisplay();

        return;
    }

    const randomIndex =
        Math.floor(Math.random() * available.length);

    currentRiddle = available[randomIndex];

    if (riddleNumberElement) {
        riddleNumberElement.textContent =
            `Riddle #${currentRiddle.id}`;
    }

    if (difficultyElement) {
        difficultyElement.textContent =
            getDifficulty(currentRiddle.id);
    }

    if (riddleQuestionElement) {
        riddleQuestionElement.textContent =
            currentRiddle.question;
    }

    updateDisplay();
}


/* =========================================================
   NORMALIZE ANSWER
   ========================================================= */

function normalize(text) {

    return String(text)
        .toLowerCase()
        .trim()
        .replace(/[.,!?]/g, "");

}


/* =========================================================
   CHECK ANSWER
   ========================================================= */

function checkAnswer() {

    if (!currentRiddle) return;

    const userAnswer =
        normalize(answerInput.value);

    if (userAnswer === "") {

        messageElement.textContent =
            "Please enter an answer.";

        return;
    }

    const correct =
        currentRiddle.answer.some(function (answer) {

            return normalize(answer) === userAnswer;

        });

    if (correct) {

        if (!solvedRiddles.includes(currentRiddle.id)) {

            solvedRiddles.push(currentRiddle.id);

            coins += 10;

            saveProgress();
            updateDisplay();

        }

        messageElement.textContent =
            "✅ Correct! +10 coins";

        answerInput.disabled = true;
        submitButton.disabled = true;
        hintButton.disabled = true;

        nextButton.style.display = "block";

    } else {

        messageElement.textContent =
            "❌ Incorrect. Try again!";

    }
}


/* =========================================================
   HINT
   ========================================================= */

function showHint() {

    if (!currentRiddle) return;

    if (hintUsed) {

        messageElement.textContent =
            "You already used the hint.";

        return;
    }

    if (coins < 5) {

        messageElement.textContent =
            "❌ You need at least 5 coins for a hint.";

        return;
    }

    coins -= 5;

    hintUsed = true;

    hintElement.textContent =
        "💡 Hint: " + currentRiddle.hint;

    hintElement.hidden = false;

    saveProgress();
    updateDisplay();

}


/* =========================================================
   BUTTON EVENTS
   ========================================================= */

if (submitButton) {

    submitButton.addEventListener(
        "click",
        checkAnswer
    );

}

if (hintButton) {

    hintButton.addEventListener(
        "click",
        showHint
    );

}

if (nextButton) {

    nextButton.addEventListener(
        "click",
        loadNextRiddle
    );

}


/* =========================================================
   ENTER KEY
   ========================================================= */

if (answerInput) {

    answerInput.addEventListener(
        "keydown",
        function (event) {

            if (event.key === "Enter") {
                checkAnswer();
            }

        }
    );

}


/* =========================================================
   START
   ========================================================= */

updateDisplay();
loadNextRiddle();